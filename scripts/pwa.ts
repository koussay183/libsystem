/**
 * Emits the shop's service worker at build time.
 *
 * Why one is needed at all: without a service worker the browser cannot fetch
 * index.html or the JavaScript chunks when the line is down, so with no
 * internet the owner does not get a degraded till — he gets the browser's
 * "no connection" page and cannot sell at all. Firestore's IndexedDB cache
 * only helps once the app is already running.
 *
 * It is written here rather than pulled from a plugin so there is no extra
 * dependency and nothing hidden: the file below is exactly what ships.
 */

/** Assets that are worth having before they are ever asked for. */
const PRECACHE_EXT = /\.(?:js|css|svg|png|webmanifest|woff2?)$/

/** Strings only third-party tag loaders contain. @see the check in generateBundle */
const TAG_MARKERS = ['googletagmanager.com', 'connect.facebook.net', 'fbevents']

/**
 * Files from public/ the shell itself shows: the icons index.html and the
 * manifest name, and the logo BrandLogo draws in the header and on the login
 * screen. public/ never enters the bundle, so without this list they were only
 * cached at runtime — and activate() empties that cache on every update, so a
 * till that went offline right after an update had a broken logo. Listed here
 * they are precached (best effort) and their bytes feed the version hash.
 */
const SHELL_PUBLIC_FILES = [
  '/manifest.webmanifest',
  '/brand/favicon-16.png',
  '/brand/favicon-32.png',
  '/brand/apple-touch-icon.png',
  '/brand/logo-on-light.png',
  '/brand/logo-on-dark.png',
  '/brand/mark.png',
  '/brand/icon-192.png',
  '/brand/icon-512.png',
  '/brand/icon-maskable-512.png',
]

/**
 * The last thing the till can put on screen.
 *
 * It is inlined into sw.js rather than shipped as a file because the situation
 * it exists for is exactly "the cache does not have what we need" — a fallback
 * that itself has to be fetched or looked up is not a fallback. Both languages
 * are hardcoded: a service worker cannot reach i18next, and this page has to
 * work at the moment nothing else does.
 *
 * It says the one thing the owner actually needs to know at that point, which
 * is that the sales already taken on this machine are not gone. Firestore's
 * queue lives in IndexedDB and is untouched by anything in this file, so
 * "clear browsing data" is the only way to lose it — hence the warning.
 */
